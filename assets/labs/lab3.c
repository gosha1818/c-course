#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>
#include <locale.h>

#define N 50 /* максимальный размер массива */

int main() {
    int a[N];     /* исходный массив */
    int b[2 * N]; /* результат: не больше 2N элементов */
    int n;        /* реальный размер исходного массива */
    int count;    /* реальный размер результата */
    int i;        /* индекс элемента */

    /* русский текст в консоли */
    setlocale(LC_ALL, "ru_RU.UTF-8");

    /* Ввод n с проверкой: если n вне диапазона, сообщить и спросить снова */
    printf("Введите размер массива n (1 <= n <= %d): ", N);
    if (scanf("%d", &n) != 1) {
        printf("Ошибка ввода: нужно целое число\n");
    }
    while (n < 1 || n > N) {
        printf("Ошибка: n должно быть от 1 до %d, введите заново: ", N);
        if (scanf("%d", &n) != 1) {
            printf("Ошибка ввода: нужно целое число\n");
        }
    }

    /* Ввод элементов массива */
    for (i = 0; i < n; i++) {
        printf("a[%d] = ", i);
        if (scanf("%d", &a[i]) != 1) {
            printf("Ошибка ввода: нужно целое число\n");
        }
    }

    /* Отбор: копируем элемент, а после отрицательного ставим 0 */
    count = 0;
    for (i = 0; i < n; i++) {
        b[count] = a[i];
        count++;
        if (a[i] < 0) {
            b[count] = 0;
            count++;
        }
    }

    /* Вывод исходного массива и результата */
    printf("Исходный массив:");
    for (i = 0; i < n; i++) {
        printf(" %d", a[i]);
    }
    printf("\nРезультат (размер %d):", count);
    for (i = 0; i < count; i++) {
        printf(" %d", b[i]);
    }
    printf("\n");
    return 0;
}
