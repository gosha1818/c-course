#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>
#include <math.h>
#include <locale.h>

int main() {
	double x;   /* верхний предел интегрирования */
	double eps; /* требуемая точность */
	double s;   /* сумма ряда - значение интеграла */
	double a;   /* текущий член ряда: (-1)^k * x^n / (n * n!) */
	double c;   /* вспомогательная величина: (-1)^k * x^n / n! */
	int m;      /* наибольшее число членов ряда M */
	int k;      /* количество просуммированных членов */
	int n;      /* степень x в текущем члене: 1, 3, 5, ... */

	/* русский текст в консоли, дробные числа вводятся через точку */
	setlocale(LC_CTYPE, "Russian");

	/* Ввод x с проверкой: должно быть числом, |x| <= 20 */
	printf("Введите x (|x| <= 20): ");
	if (scanf("%lf", &x) != 1) {
		printf("Ошибка ввода: x должно быть числом\n");
		return 1;
	}
	if (fabs(x) > 20.0) {
		/* при больших |x| из-за округления ряд теряет точность */
		printf("Ряд теряет точность при данном значении x\n");
		return 1;
	}

	/* Ввод числа членов ряда M с проверкой: целое, M >= 1 */
	printf("Введите число членов ряда (M >= 1): ");
	if (scanf("%d", &m) != 1 || m < 1) {
		printf("Ошибка ввода: M должно быть целым числом, M >= 1\n");
		return 1;
	}

	/* Ввод точности eps с проверкой: 0 < eps < 1 */
	printf("Введите точность (0<eps<1): ");
	if (scanf("%lf", &eps) != 1 || eps <= 0 || eps >= 1) {
		printf("Ошибка ввода: eps должно быть числом, 0 < eps < 1\n");
		return 1;
	}

	/* Подготовка к циклу: первый член ряда равен x (n = 1, c = x) */
	s = 0;
	c = x;
	n = 1;
	k = 0;

	/* Итерационный цикл: не более M членов, выход - по break */
	while (k < m) {
		a = c / n; /* очередной член ряда */

		/* 1) член меньше eps по модулю - точность достигнута */
		if (fabs(a) < eps) {
			printf("Достигнута заданная точность\n");
			break;
		}

		/* 2) член не меняет сумму - точность double исчерпана */
		if (s + a == s) {
			printf("Член ряда не влияет на сумму, "
				   "дальнейшее повышение точности невозможно\n");
			break;
		}

		s += a; /* добавляем член к сумме */
		k++;    /* считаем просуммированные члены */

		/* переход к следующему члену по рекуррентной формуле:
		   c(k+1) = -c(k) * x^2 / ((n + 1) * (n + 2)) */
		c = -c * x * x / ((n + 1.0) * (n + 2.0));
		n += 2;
	}

	/* Цикл закончился по счётчику: просуммированы все M членов */
	if (k == m) {
		printf("Просуммированы все члены ряда M = %d\n", m);
	}

	/* Вывод результата */
	printf("I(%g) = %.10f\n", x, s);
	printf("Просуммировано членов: %d\n", k);
	return 0;
}
